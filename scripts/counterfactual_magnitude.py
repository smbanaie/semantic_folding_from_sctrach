"""Counterfactual relevance-aligned magnitude intervention (SIGIR-Final-Tasks Item 1).

Builds on scripts/magnitude_perturbation.py (rank-preserving sensitivity) by adding
the CAUSAL arm the reviewer's #1 / #38 requires:

  World+ : within each rank bucket, amplify the relevant document's score margin
           above the bucket's non-relevant mean (rho in {1.25,1.5,2.0}); rank preserved.
  World- : within each rank bucket, push the relevant document BELOW the non-relevant
           mean (reverse the margin); rank preserved.

Because ranks are held fixed by construction, RRF (rank-only) output is identical
across all worlds => any CombSUM/CombMNZ change is attributable to magnitude, and the
direction (World+ > orig > World-) causally implicates relevance-aligned magnitude.

Also reproduces/extends the descriptive H3a arm:
  * rank-conditioned relevance probability P(y=1 | delta_k large) vs small
  * E[s|y=1,r] - E[s|y=0,r] per rank bucket

Inputs: docs/papers/Journal A/appendix_alpha/<ds>_comp_{1.0,0.0}_n100.json
        (generated by scripts/gen_component_traces_n100.py)
        <run>/query_gold.json

Outputs: docs/papers/Journal A/appendix_stats/counterfactual_magnitude.{json,md}
         (SIGIR-Final-Results.md is filled in separately by the user after review)
"""
